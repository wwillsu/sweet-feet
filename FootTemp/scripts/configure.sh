#!/bin/sh
# Points the app at this Mac's Wi-Fi address and re-syncs thresholds (config.json) and the
# Daily tracker's bundled data (data/dashboard.json) from foot-ulcer-ews.
# Re-run when your IP changes (new network) or the web app's data changes, then rebuild.
# Override the address: CONVEX_URL=http://host:3210 scripts/configure.sh
set -eu
cd "$(dirname "$0")/.."
src=../foot-ulcer-ews
if [ -f "$src/config.json" ]; then cp "$src/config.json" FootTemp/config.json; fi
if [ -f "$src/data/dashboard.json" ]; then cp "$src/data/dashboard.json" FootTemp/dashboard.json; fi
if [ -z "${CONVEX_URL:-}" ]; then
  ip=$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null || true)
  CONVEX_URL="http://${ip:-127.0.0.1}:3210"
fi
# xcconfig treats // as a comment, so the slashes are split with $()
printf '// Generated by scripts/configure.sh\nCONVEX_URL = %s\n' "$(echo "$CONVEX_URL" | sed 's#//#/$()/#')" > Config.xcconfig
echo "App default backend: $CONVEX_URL"
