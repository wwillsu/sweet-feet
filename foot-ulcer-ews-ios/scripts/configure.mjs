// Run before `expo start`:
//  1. copies the thresholds from ../foot-ulcer-ews/config.json (the single source of truth)
//  2. writes EXPO_PUBLIC_CONVEX_URL to .env.local, pointing at this Mac's Wi-Fi address,
//     because the phone can't reach 127.0.0.1. Override with CONVEX_URL=... npm start
import { copyFileSync, existsSync, writeFileSync } from "node:fs";
import { networkInterfaces } from "node:os";

const root = new URL("..", import.meta.url);
const shared = new URL("../foot-ulcer-ews/config.json", root);
if (existsSync(shared)) copyFileSync(shared, new URL("src/lib/config.json", root));
else console.warn("! ../foot-ulcer-ews/config.json not found; using the bundled copy");

function lanAddress() {
  const ifaces = networkInterfaces();
  const order = ["en0", "en1", ...Object.keys(ifaces)];
  for (const name of order) {
    const hit = (ifaces[name] ?? []).find((a) => a.family === "IPv4" && !a.internal);
    if (hit) return hit.address;
  }
  return null;
}

const ip = lanAddress();
const url = process.env.CONVEX_URL ?? (ip ? `http://${ip}:3210` : null);
if (!url) {
  console.error("! No Wi-Fi address found. Connect to Wi-Fi or run: CONVEX_URL=http://<mac-ip>:3210 npm start");
  process.exit(1);
}
writeFileSync(new URL(".env.local", root), `# Generated by scripts/configure.mjs\nEXPO_PUBLIC_CONVEX_URL=${url}\n`);
console.log(`Convex backend for the phone: ${url}`);
